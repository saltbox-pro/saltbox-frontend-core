/**
 * Имя файла инженер не придумывает: в базовом режиме оно выводится из названия
 * шаблона. Транслитерация нужна потому, что название чаще всего русское, а имя
 * файла обязано укладываться в `TEMPLATE_FILE_NAME_PATTERN` — только латиница,
 * цифры, «_» и «-».
 */
const TRANSLITERATION: Readonly<Record<string, string>> = {
  а: "a",
  б: "b",
  в: "v",
  г: "g",
  д: "d",
  е: "e",
  ё: "e",
  ж: "zh",
  з: "z",
  и: "i",
  й: "i",
  к: "k",
  л: "l",
  м: "m",
  н: "n",
  о: "o",
  п: "p",
  р: "r",
  с: "s",
  т: "t",
  у: "u",
  ф: "f",
  х: "h",
  ц: "c",
  ч: "ch",
  ш: "sh",
  щ: "sch",
  ъ: "",
  ы: "y",
  ь: "",
  э: "e",
  ю: "yu",
  я: "ya",
};

/**
 * Имя файла по названию шаблона. Если после транслитерации не осталось ни
 * одного допустимого символа (название на иероглифах, одни знаки препинания),
 * возвращает пустую строку — такое название редактор просит заменить или
 * задать имя вручную в расширенных параметрах.
 */
export function deriveTemplateFileName(title: string): string {
  const transliterated = [...title.toLowerCase()]
    .map((char) => TRANSLITERATION[char] ?? char)
    .join("");

  return transliterated
    .replace(/[^a-z0-9_-]+/g, "_")
    .replace(/_{2,}/g, "_")
    .replace(/^[_-]+|[_-]+$/g, "");
}
